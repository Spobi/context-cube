/**
 * One row in a row list. `compact` keeps only the name and when to open it (the
 * routing instruction), for an always-loaded block over its ceiling.
 */
export function rowListLine(row: Row, cpt: number, withPath: string, sizes = true, compact = false): string {
  const h = row.root?.header;
  const summary = h ? h.summary : "(no root summary)";
  if (compact) return `- ${row.id} ${row.name}: open when ${h?.read_when ? h.read_when.replace(/^./, (c) => c.toLowerCase()) : summary} → ${withPath}${row.relDir}/ROW.md`;
  const when = h?.read_when ? ` Open when: ${h.read_when}` : "";
  const size = sizes ? ` (${countLabel(row)}, ~${fmtInt(rowTokens(row, cpt))} tokens)` : "";
  return `- ${row.id} ${row.name}: ${summary}${when}${size} → ${withPath}${row.relDir}/ROW.md`;
}

export function cubeMd(cube: Cube, config: CubeConfig): string {
  const cpt = config.tokens.charsPerToken;
  const lines = [
    GENERATED_NOTE,
    "# Project memory (Context Cube)",
    "",
    "This folder is the project's memory: rules, history, invariants (rules that must never be broken), features, systems, and anything else worth remembering. Read it top-down: short summaries first, detail only when a task needs it.",
    "",
    "## How to read it",
    "",
    ...PROTOCOL,
    "",
    "## Layout",
    "",
    "- A **row** (Y00–Y99) is one area: rules, history, invariants, a feature, a system, or a catalog. Y00 is always the rules row.",
    "- A **box** (X001…) is one item in a row. X000 is the row's root, describing the whole row.",
    "- Every box has the same five **drawers**: Z0 overview (with a read-when line), Z1 invariants, Z2 code, Z3 history, Z4 detail. Only Z0 is required.",
    "- Ids look like `Y05.X003` (a box) and `Y05.X003.Z1` (a drawer). Inline references look like `[[Y05.X003]]`.",
    `- Old references such as "§21" resolve with \`${TOOL_COMMAND} resolve "§21"\`.`,
    "",
    "## Rows",
    "",
  ];
  if (!cube.rows.length) lines.push("No rows yet.");
  for (const row of cube.rows) lines.push(rowListLine(row, cpt, ""));
  lines.push("", "## Commands", "", `Run from the project root: \`${TOOL_COMMAND} <command>\`. \`${TOOL_COMMAND} --help\` lists them all.`, "");
  return `${lines.join("\n")}`;
}
